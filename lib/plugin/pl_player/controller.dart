    lastPlaybackSpeed = playbackSpeed;

    if (speed == _videoPlayerController?.state.rate) return;

    await _videoPlayerController?.setRate(speed);
    if (!isLive) _playbackSpeed.value = speed;
    _updatePlaybackState();
    if (danmakuController != null) {
      try {
        danmakuController?.updateOption(
          danmakuController!.option.copyWith(
            duration: DanmakuOptions.danmakuDuration / speed,
            staticDuration: DanmakuOptions.danmakuStaticDuration / speed,
          ),
        );
      } catch (_) {}
    }
  }

  /// 播放视频
  Future<void> play({bool repeat = false, bool hideControls = true}) async {
    if (_playerCount == 0 || _taskScope.closed) return;
    if (_btrFailedGeneration == _btrOpenGeneration) return;
    final intent = _seekIntent.requestPlaying(true);
    final player = _videoPlayerController;
    // 播放时自动隐藏控制条
    controls = !hideControls;
    // repeat为true，将从头播放
    var seekRequest = _seekToRequest;
    if (repeat) {
      final seeking = seekTo(Duration.zero, isSeek: false);
      seekRequest = _seekToRequest;
      await seeking;
    }

    if ((repeat && seekRequest != _seekToRequest) ||
        !_seekIntent.isCurrent(intent) ||
        !identical(player, _videoPlayerController)) {
      return;
    }
    if (_btrPlayback?.readRecovery.abnormalCompleted == true) {
      // An EOF correction is queued behind this source open. Awaiting a
      // second open here would wait on our own source operation.
      if (_processing && _seekIntent.pendingTarget != null) return;
      await refreshPlayer();
      return;
    }
    if (player != null && _seekIntent.pendingTarget != null) {
      await _resumeAfterSeek(player);
    } else {
      await player?.play();
    }
    if (!_seekIntent.isCurrent(intent)) return;

    audioSessionHandler?.setActive(true);

    playerStatus = .playing;
  }

  /// 暂停播放
  Future<void> pause({
    bool notify = true,
    bool isInterrupt = false,
    bool preserveIntent = false,
  }) async {
    final intent = preserveIntent
        ? _seekIntent.revision
        : _seekIntent.requestPlaying(false);
    await _videoPlayerController?.pause();
    if (!_seekIntent.isCurrent(intent)) return;
    playerStatus = .paused;

    // 主动暂停时让出音频焦点
    if (!isInterrupt) {
      audioSessionHandler?.setActive(false);
    }
  }

